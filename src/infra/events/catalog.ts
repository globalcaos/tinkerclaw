/**
 * The event catalog — TINKER_UI_DESIGN_BIBLE/logging.md §4 as data (§9 step 1).
 *
 * Single source in code for what may ever be recorded. The writer (logging.md §7.5, §9 step 3)
 * will reject any name or field key this catalog does not declare (counted, never thrown), and
 * the schema module (§9 step 2) seeds the database's `catalog` table and generates per-event
 * views from these rows. logging.md §4 is the human-readable a-priori declaration (L2: declare
 * before emit); `scripts/bible/logging-catalog.mjs` — this optic's `verify:` — checks that the
 * two agree in BOTH directions on every run, so neither can drift silently.
 *
 * FORMAT CONTRACT: scripts/bible/logging-catalog.mjs parses this file TEXTUALLY (it runs under
 * plain node, with no TypeScript loader). Every row keeps its first three properties — the
 * event's dotted identifier, its kind and its retention class — double-quoted, each on its own
 * line, in that order. Never give a declared field key one of those three property names;
 * catalog.test.ts enforces both halves of this contract.
 *
 * PII (logging.md L4): a string-typed field is "enum" (a closed set) or "id" (pattern-limited,
 * at most 64 characters); there is no free-text field type, so the writer can drop anything else
 * mechanically. "json" is reserved for the structured objects §4 itself names (the algorithm
 * ledger's metrics/provenance/config, histogram buckets, per-reason counters), which carry no
 * free text by their own rules.
 */

export const EVENT_KINDS = ["sample", "span", "transition", "outcome", "rollup", "mark"] as const;
export type EventKind = (typeof EVENT_KINDS)[number];

export const RETENTION_CLASSES = ["hot", "event", "research", "debug"] as const;
export type RetentionClass = (typeof RETENTION_CLASSES)[number];

/** L4: no free-text type exists. Strings are "enum" (closed set) or "id" (pattern-limited). */
export const FIELD_TYPES = ["number", "boolean", "enum", "id", "json"] as const;
export type CatalogFieldType = (typeof FIELD_TYPES)[number];

