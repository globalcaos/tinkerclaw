export interface CatalogEvent {
  /** Stable dotted name, `<domain>.<object>[.<verb>]` (L1); the primary key. */
  readonly name: string;
  /** §4 Kinds: sample, span, transition, outcome, rollup, mark. */
  readonly kind: EventKind;
  /** Retention class (§7.4): hot, event, research, debug. */
  readonly retention: RetentionClass;
  /** The J-series paper whose metric this row carries (§4.12), else null. */
  readonly paper: JSeriesPaper | null;
  /** The question this event exists to answer (L2). */
  readonly question: string;
  /** What `label` — the one categorical dimension — carries, or null when unused. */
  readonly label: string | null;
  /** What `dur_ms` measures, or null when unused; every span states it. */
  readonly durMs: string | null;
  /** What n1..n4 carry (unit in the name, L1), or null when unused. */
  readonly n1: string | null;
  readonly n2: string | null;
  readonly n3: string | null;
  readonly n4: string | null;
  /** Declared `fields` JSON keys with their types (L4). */
  readonly fields: Readonly<Record<string, CatalogFieldType>>;
  /** May this row arrive through `logs.ingest` from the UI (§8.2)? Gateway events never. */
  readonly uiIngestable: boolean;
}

