#!/usr/bin/env node
// tinker-ui/scripts/gen-vendor-marks.mjs
// FORK 2026-08-04 (the architect): generate src/panels/vendor-marks.ts from the official
// brand SVGs, rather than hand-copying 3,400 characters of path data (which is
// exactly the class of transcription nobody can review and everybody gets wrong).
//
// Source: @lobehub/icons-static-svg — the MONOCHROME (currentColor) variants,
// tinted with each vendor's EEG trace colour. Re-fetch + regenerate with:
//   node tinker-ui/scripts/gen-vendor-marks.mjs
//
// FORK 2026-08-04 #2 (the architect: "Kimi, deepseek and qwen do not have a color yet
// visible in the models panel"). The first pass used the "-color" variants — the
// real brand artwork — and at 14px on the #2a2318 paper they FAILED: Kimi's mark
// is a white K with a 2px blue dot, so it read as colourless, and DeepSeek's
// #4D6BFE and Qwen's #6336E7 are dark blues that sink into a dark brown panel.
// Brand artwork is drawn for white backgrounds; this panel is not one.
//
// So the logo is now TINTED with the vendor's trace colour. Two wins: every mark
// is legible at 14px, and a row's logo, its glow and its EEG trace are literally
// the same colour — the identity is readable at a glance instead of decoded. This
// is the same choice already made for the xai mark (rendered white because its
// black brand is invisible here) and the openai mark (flat #10a37f).
import { writeFileSync } from "node:fs";

const SRC = "https://unpkg.com/@lobehub/icons-static-svg@latest/icons";

// vendor key → { icon, brand, trace, why }
// `trace` values come from scripts/pick-trace-colors.mjs (OKLab farthest-point).
const VENDORS = [
  {
    key: "kimi",
    icon: "kimi",
    label: "Kimi",
    brand: "#1783FF",
    trace: "#07B2FE",
    why: "azure, same hue family as the #1783FF logo, pushed cyan-ward to clear the 256-270 pile-up",
  },
  {
    key: "qwen",
    icon: "qwen",
    label: "Qwen",
    brand: "#6336E7",
    trace: "#C382FB",
    why: "violet, the light side of the #6336E7/#6F69F7 brand gradient",
  },
  {
    key: "glm",
    icon: "zhipu",
    label: "GLM",
    brand: "#3859FF",
    trace: "#80EE24",
    why: "NOT a brand colour — #3859FF is one degree off DeepSeek's #4D6BFE, so staying on-brand was impossible; green was the only genuinely empty region",
  },
  {
    key: "deepseek",
    icon: "deepseek",
    label: "DeepSeek",
    brand: "#4D6BFE",
    trace: "#4D6BFE",
    why: "authentic brand blue, already shipped and already distinct",
  },
];

/**
 * Inline an SVG at 14px, tinted with `tint`, namespacing any gradient ids so
 * repeated inlining cannot collide.
 *
 * The lobehub monochrome marks carry fill="currentColor" on the root, which would
 * inherit the panel's text colour and make every vendor look identical. Pinning
 * the fill to the vendor's trace colour is the whole point of this pass.
 */
function normalize(svg, key, tint) {
  let out = svg
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .replace(/\s(height|width)="1em"/g, "")
    .replace(/\sstyle="[^"]*"/g, "")
    .replace(/fill="currentColor"/g, `fill="${tint}"`)
    .replace(/<svg /, `<svg width="14" height="14" `);
  if (!out.includes(tint)) {
    // Fail loud rather than emit a mark that inherits an arbitrary colour — a
    // silently-untinted logo is exactly the bug this pass exists to fix.
    console.error(`${key}: no currentColor fill to tint — mark would be uncoloured`);
    process.exit(1);
  }
  // namespace gradient / clipPath ids: id="a" → id="kimi-a", url(#a) → url(#kimi-a)
  const ids = [...out.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    out = out.replaceAll(`id="${id}"`, `id="${key}-${id}"`);
    out = out.replaceAll(`url(#${id})`, `url(#${key}-${id})`);
  }
  return out.trim();
}

const marks = {};
for (const v of VENDORS) {
  const res = await fetch(`${SRC}/${v.icon}.svg`);
  if (!res.ok) {
    console.error(`fetch failed for ${v.icon}: ${res.status}`);
    process.exit(1);
  }
  marks[v.key] = normalize(await res.text(), v.key, v.trace);
  console.error(`${v.key}: ${marks[v.key].length} chars`);
}

const body = `// tinker-ui/src/panels/vendor-marks.ts
// GENERATED by scripts/gen-vendor-marks.mjs — do not hand-edit the path data.
//
// FORK 2026-08-04 (the architect): the OpenRouter models (Kimi, Qwen, GLM, DeepSeek) all
// report provider "openrouter", so every provider-keyed lookup gave them the same
// anonymous grey dot and, on the EEG, the same anonymous grey trace. Identity for
// these lives at the MODEL level, not the provider level — hence this table and
// \`vendorOfModel()\`.
//
// Logos are the official brand marks (@lobehub/icons-static-svg), TINTED with each
// vendor's trace colour rather than its brand colour. The brand artwork is drawn
// for white backgrounds and failed on this one: Kimi's mark is a white K, and
// DeepSeek's and Qwen's dark blues sank into the #2a2318 paper at 14px. Tinting
// also makes a row's logo, glow and EEG trace the same colour.
//
// Trace colours are NOT the brand colours: four blue-indigo brands on one
// seismograph are four unreadable traces. They come from the OKLab farthest-point
// sampler in scripts/pick-trace-colors.mjs.

export interface VendorMark {
  label: string;
  /** Official brand colour, for reference and for the logo itself. */
  brand: string;
  /** EEG trace colour — chosen for separability, see why. */
  trace: string;
  why: string;
  svg: string;
}

export const VENDOR_MARKS: Record<string, VendorMark> = {
${VENDORS.map(
  (v) => `  ${v.key}: {
    label: ${JSON.stringify(v.label)},
    brand: ${JSON.stringify(v.brand)},
    trace: ${JSON.stringify(v.trace)},
    why: ${JSON.stringify(v.why)},
    svg: ${JSON.stringify(marks[v.key])},
  },`,
).join("\n")}
};

/**
 * Resolve a model id (or bare model name) to a vendor key.
 *
 * Matches on the id text rather than the provider segment, because
 * "openrouter/moonshotai/kimi-k3" carries its identity in the middle and last
 * segments. Returns undefined when nothing matches, so callers keep their
 * existing provider-level fallback.
 */
export function vendorOfModel(id: string): string | undefined {
  const lo = (id || "").toLowerCase();
  // ORDER IS LOAD-BEARING — first match wins, and vendor names appear inside
  // OTHER vendors' model names. deepseek MUST be tested before qwen, or
  // "deepseek/deepseek-r1-distill-qwen-32b" paints a Qwen mark on a DeepSeek
  // model. Distills are the general hazard here: any \`<vendor-a>-distill-<vendor-b>\`
  // id contains two vendor tokens, and the owning vendor is the one in the
  // PROVIDER segment, not the one in the architecture suffix.
  if (/deepseek/.test(lo)) return "deepseek";
  if (/kimi|moonshot/.test(lo)) return "kimi";
  if (/glm|zhipu|z-ai/.test(lo)) return "glm";
  if (/qwen|qwq/.test(lo)) return "qwen";
  return undefined;
}

/** Official mark for a model id, or undefined when the model is not one of ours. */
export function vendorMarkFor(id: string): VendorMark | undefined {
  const key = vendorOfModel(id);
  return key ? VENDOR_MARKS[key] : undefined;
}
`;

writeFileSync(new URL("../src/panels/vendor-marks.ts", import.meta.url), body);
console.error("wrote src/panels/vendor-marks.ts");
