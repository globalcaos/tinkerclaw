/**
 * Pad the registry to `total` cards with invented, off-topic hobby cards, so the flat question can be tried at the size of a
 * real registry (about 210) without any of the extra cards being a fit for the tasks above. Deterministic. Returns `cards`
 * unchanged when `total` is not larger.
 */
export function padCards(cards, total) {
  if (!(total > cards.length)) return cards;
  const topics = [
    "gardening",
    "astronomy",
    "chess",
    "knitting",
    "aquariums",
    "birdwatching",
    "origami",
    "pottery",
    "sailing",
    "beekeeping",
    "baking",
    "cycling",
    "hiking",
    "calligraphy",
    "juggling",
    "stamp collecting",
    "coin collecting",
    "fossils",
    "kites",
    "jigsaw puzzles",
    "bonsai",
    "woodturning",
  ];
  const actions = [
    ["identify", "Identify things in {t} from a short description."],
    ["logbook", "Keep a logbook for {t}: entries, dates and notes."],
    ["season", "Plan a season of activities in {t} for a beginner."],
    ["rules", "Explain the rules and terms of {t} in plain words."],
    ["starter", "Suggest a first small project in {t} and list what it needs."],
    ["gear", "Track the equipment owned for {t} and what is worn out."],
    ["clubs", "Suggest clubs and meetups for {t}."],
    ["sketch", "Draw simple diagrams that explain a technique in {t}."],
    ["quiz", "Quiz the user about {t} at a chosen level."],
  ];
  const out = [...cards];
  for (const t of topics) {
    for (const [slug, text] of actions) {
      if (out.length >= total) return out;
      const name = `${t.replace(/ /g, "-")}-${slug}`;
      out.push({
        id: `skill:${name}`,
        kind: "skill",
        name,
        family: "hobbies",
        purpose: text.replace("{t}", t),
        structure: "",
        alsoServed: [],
        version: 1,
        status: "active",
        origin: "seed",
      });
    }
  }
  return out;
}
